/**
 * Object storage — the contract every storage adapter implements, plus an in-memory development/test adapter
 * (rules.md §6). No real provider exists yet: modules.md §1 plans "AWS S3 / Cloudflare R2" with SSE-KMS, but neither
 * is chosen, no bucket or credentials exist and the AWS SDK is not a dependency. A real adapter must implement exactly
 * this interface, sign URLs that bind the content type and length, and encrypt objects at rest.
 *
 * Interface:
 *   createUploadUrl({ key, contentType, contentLength, expiresInSeconds })
 *     → { url, method: 'PUT', headers, expiresAt }   single-purpose PUT for one key; ≤ 15 min (rules.md §22);
 *                                                    single-use: must refuse to overwrite an existing object
 *                                                    (S3/R2: sign `If-None-Match: *`)
 *   createDownloadUrl({ key, expiresInSeconds })
 *     → { url, expiresAt }                           single-purpose GET for one key; ≤ 5 min (rules.md §22)
 *   inspect(key, { prefixBytes })
 *     → { contentLength, contentType, etag, prefix: Buffer } | null   what was stored (null = nothing yet); `etag`
 *       identifies the exact object, so callers can detect a swap
 *
 * Signed URLs are handed to the caller once and never stored. Keys are generated by the calling module, never taken
 * from a client; `assertSafeKey` rejects anything that could escape its prefix.
 */
import { createHash, randomUUID } from 'node:crypto';

export const MAX_UPLOAD_URL_SECONDS = 15 * 60;
export const MAX_DOWNLOAD_URL_SECONDS = 5 * 60;

const SAFE_KEY = /^[a-z0-9]+(?:[/._-][a-z0-9]+)*$/i;

export function assertSafeKey(key) {
  if (typeof key !== 'string' || key.length > 512 || !SAFE_KEY.test(key)) {
    throw new Error('Unsafe storage key');
  }
}

function expiry(now, seconds, max) {
  if (!Number.isInteger(seconds) || seconds < 1 || seconds > max) throw new Error('Invalid signed URL lifetime');
  return new Date(now().getTime() + seconds * 1000);
}

/**
 * Development/test adapter: objects live in this process's memory and are lost on restart. Its URLs use the
 * `memory-storage:` scheme so nobody mistakes them for real S3 URLs — a browser cannot upload to them. Tests (and
 * local experiments) "upload" with `completeUpload(url, { body, contentType })`, which enforces what a real signed
 * URL would: the method's key, expiry, content type and exact length.
 */
export function createMemoryStorage({ now = () => new Date() } = {}) {
  const objects = new Map();
  const grants = new Map();

  return {
    name: 'memory',
    async createUploadUrl({ key, contentType, contentLength, expiresInSeconds }) {
      assertSafeKey(key);
      const expiresAt = expiry(now, expiresInSeconds, MAX_UPLOAD_URL_SECONDS);
      const token = randomUUID();
      grants.set(token, { key, contentType, contentLength, expiresAt, method: 'PUT' });
      return {
        url: `memory-storage://upload/${token}`,
        method: 'PUT',
        headers: { 'Content-Type': contentType, 'Content-Length': String(contentLength) },
        expiresAt,
      };
    },
    async createDownloadUrl({ key, expiresInSeconds }) {
      assertSafeKey(key);
      const expiresAt = expiry(now, expiresInSeconds, MAX_DOWNLOAD_URL_SECONDS);
      const token = randomUUID();
      grants.set(token, { key, expiresAt, method: 'GET' });
      return { url: `memory-storage://download/${token}`, expiresAt };
    },
    async inspect(key, { prefixBytes = 16 } = {}) {
      assertSafeKey(key);
      const object = objects.get(key);
      if (!object) return null;
      return {
        contentLength: object.body.length,
        contentType: object.contentType,
        etag: createHash('sha256').update(object.body).digest('hex'),
        prefix: object.body.subarray(0, prefixBytes),
      };
    },
    /** Plays the part of the client's PUT to an upload URL. Throws like a provider would refuse the request. */
    completeUpload(url, { body, contentType }) {
      const token = /^memory-storage:\/\/upload\/([\w-]+)$/.exec(url)?.[1];
      const grant = token && grants.get(token);
      if (!grant || grant.method !== 'PUT') throw new Error('Unknown upload URL');
      if (grant.expiresAt <= now()) throw new Error('Upload URL expired');
      if (contentType !== grant.contentType) throw new Error('Content-Type does not match the signed URL');
      if (body.length !== grant.contentLength) throw new Error('Content-Length does not match the signed URL');
      // Single use, like a signed `If-None-Match: *`: the URL can't overwrite what it already uploaded.
      if (objects.has(grant.key)) throw new Error('Object already exists');
      objects.set(grant.key, { body: Buffer.from(body), contentType });
    },
    /** Test helper: what a download URL would serve. */
    readDownload(url) {
      const token = /^memory-storage:\/\/download\/([\w-]+)$/.exec(url)?.[1];
      const grant = token && grants.get(token);
      if (!grant || grant.method !== 'GET' || grant.expiresAt <= now()) throw new Error('Invalid download URL');
      return objects.get(grant.key)?.body ?? null;
    },
    /** Test helper: stores an object directly, bypassing the signed URL (e.g. to simulate a tampered upload). */
    putObject(key, { body, contentType }) {
      assertSafeKey(key);
      objects.set(key, { body: Buffer.from(body), contentType });
    },
    reset() {
      objects.clear();
      grants.clear();
    },
  };
}

/**
 * Picks the adapter for this process, or null when storage is not available. Production never gets the memory
 * adapter — there is no real provider yet, so production fails safe (callers answer 503) instead of handing out URLs
 * that go nowhere.
 * @param {{ driver?: string, nodeEnv: string }} config
 */
export function selectStorage({ driver, nodeEnv }) {
  if (nodeEnv === 'production') return null;
  if (driver === 'memory') return createMemoryStorage();
  return null;
}
